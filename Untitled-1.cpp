// 变量的定义
#include <iostream>
using namespace std;

int main() {
    // 定义一个整型变量
    int a = 10;
    // 定义一个浮点型变量
    float b = 3.14;
    // 定义一个字符型变量
    char c = 'A';
    // 定义一个布尔型变量
    bool d = true;

    // 输出变量的值
    cout << "整数型变量 a 的值: " << a << endl;
    cout << "浮点型变量 b 的值: " << b << endl;
    cout << "字符型变量 c 的值: " << c << endl;
    cout << "布尔型变量 d 的值: " << d << endl;

    return 0;
}

